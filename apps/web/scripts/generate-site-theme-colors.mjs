import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../src/components/blast-ui/blast-ui.css", import.meta.url), "utf8");
const target = new URL("../src/lib/site-theme-colors.generated.ts", import.meta.url);
const tokens = {
  MISSION_THEME_COLOR: "--brand-mission-canvas",
  LANDING_THEME_COLOR: "--brand-landing-canvas",
  INSTALLED_THEME_COLOR: "--brand-installed-canvas",
  SHELL_STATUS_LIGHT: "--brand-status-light",
  SHELL_STATUS_DARK: "--brand-status-dark",
};

const exports = Object.entries(tokens).map(([name, token]) => {
  const declaration = new RegExp(`^\\s*${token}: (#[0-9a-f]{6});$`, "m").exec(css);
  if (!declaration) throw new Error(`Missing hex color for ${token} in blast-ui.css`);
  return `export const ${name} = "${declaration[1]}";`;
});
const output = ["// Generated by npm run generate:site-theme-colors from blast-ui.css.", ...exports, ""].join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) {
    throw new Error("Run npm run generate:site-theme-colors to update the browser theme colors.");
  }
} else {
  writeFileSync(target, output);
}
