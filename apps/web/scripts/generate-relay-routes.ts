/**
 * Writes one Next route file per relayed endpoint, from the route tables:
 * private routes, cron routes and first-party reads. `--check` fails on any drift.
 *
 *   npm run generate:relay-routes -w @blast/web            # write
 *   npm run generate:relay-routes -w @blast/web -- --check # verify only
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { CRON_ROUTES, cronRoute } from "@blast/core/modules/backend-api/cron-routes.ts";
import { PRIVATE_ROUTES } from "@blast/core/modules/backend-api/private-routes.ts";
import type { RoutePath } from "@blast/core/modules/backend-api/route-path.ts";
import { FIRST_PARTY_WEB_PATHS } from "@blast/server/modules/partner-api/v1/paths.ts";

const APP = fileURLToPath(new URL("../src/app/", import.meta.url));
const MARKER = "// Generated by apps/web/scripts/generate-relay-routes.ts from the route tables. Do not edit.";
const METHOD_ORDER = ["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE"];
const DEFAULT_WORK_BUDGET_MS = 30_000;
/** The relay aborts five seconds after the work budget; Next keeps five more to answer. */
const RELAY_MARGIN_SECONDS = 10;

type Relay = "private" | "cron" | "first-party";
type RelayRoute = { path: RoutePath; relay: Relay; methods: Set<string>; workBudgetMs?: number };

const RELAY_IMPORT: Record<Relay, string> = {
  private: 'import { backendPrivateRequest } from "@blast/server/private/relay.ts";',
  cron: 'import { backendCronRequest } from "@blast/server/cron/relay.ts";',
  "first-party": 'import { backendFirstPartyRead } from "#web/modules/partner-api/v1/relay.ts";',
};
const RELAY_FUNCTIONS = /\b(backendPrivateRequest|backendCronRequest|backendFirstPartyRead)\b/;

/** Every relayed endpoint, one entry per path. */
function relayRoutes(): readonly RelayRoute[] {
  const routes = new Map<string, RelayRoute>();
  const add = (path: RoutePath, relay: Relay, method: string, workBudgetMs?: number) => {
    const route = routes.get(path) ?? { path, relay, methods: new Set<string>() };
    if (route.relay !== relay) throw new Error(`${path} is declared by both the ${route.relay} and ${relay} tables.`);
    route.methods.add(method);
    if (workBudgetMs !== undefined) route.workBudgetMs = Math.max(route.workBudgetMs ?? 0, workBudgetMs);
    routes.set(path, route);
  };
  for (const route of PRIVATE_ROUTES) {
    if (!route.ssrOnly) add(route.path, "private", route.method, route.workBudgetMs ?? DEFAULT_WORK_BUDGET_MS);
  }
  for (const path of CRON_ROUTES) {
    for (const method of ["GET", "HEAD"]) add(path, "cron", method, cronRoute(method, path)!.workBudgetMs);
  }
  for (const path of FIRST_PARTY_WEB_PATHS) add(path, "first-party", "GET");
  return [...routes.values()];
}

function relayFileSource(route: RelayRoute): string {
  const methods = METHOD_ORDER.filter((method) => route.methods.has(method));
  const unknown = [...route.methods].filter((method) => !METHOD_ORDER.includes(method));
  if (unknown.length) throw new Error(`${route.path} declares unsupported methods ${unknown.join(", ")}.`);
  const config = ['export const runtime = "nodejs";', 'export const dynamic = "force-dynamic";'];
  if (route.workBudgetMs !== undefined) {
    config.push(`export const maxDuration = ${Math.ceil(route.workBudgetMs / 1000) + RELAY_MARGIN_SECONDS};`);
  }
  const handlers =
    route.relay === "first-party"
      ? [
          // Next passes route context second, where the relay takes an environment override.
          "export function GET(request: Request): Promise<Response> {",
          "  return backendFirstPartyRead(request);",
          "}",
        ]
      : methods.map(
          (method) =>
            `export const ${method} = ${route.relay === "cron" ? "backendCronRequest" : "backendPrivateRequest"};`,
        );
  return [MARKER, RELAY_IMPORT[route.relay], "", ...config, "", ...handlers, ""].join("\n");
}

/** Route files by URL path, with route groups such as `(mission-control)` left out. */
function existingRouteFiles(directory = APP, url = ""): Map<string, string> {
  const found = new Map<string, string>();
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      const segment = /^\(.+\)$/.test(entry.name) ? "" : `/${entry.name}`;
      for (const [childUrl, file] of existingRouteFiles(path, url + segment)) found.set(childUrl, file);
    } else if (entry.name === "route.ts") {
      found.set(url || "/", path);
    }
  }
  return found;
}

function webPath(path: RoutePath): string {
  return path.replace(/:(\w+)/g, "[$1]");
}

type Plan = { write: Map<string, string>; remove: string[]; handWritten: string[] };

/** What the app directory must hold: an existing file keeps its place, including inside a route group. */
function relayPlan(): Plan {
  const existing = existingRouteFiles();
  const write = new Map<string, string>();
  for (const route of relayRoutes()) {
    const url = webPath(route.path);
    const file = existing.get(url) ?? join(APP, url, "route.ts");
    write.set(file, relayFileSource(route));
  }
  const remove: string[] = [];
  const handWritten: string[] = [];
  for (const file of existing.values()) {
    const source = readFileSync(file, "utf8");
    if (write.has(file)) {
      if (!source.startsWith(MARKER)) handWritten.push(file);
    } else if (source.startsWith(MARKER)) remove.push(file);
    else if (RELAY_FUNCTIONS.test(source)) handWritten.push(file);
  }
  return { write, remove, handWritten };
}

/** Every difference between the app directory and the route tables; empty when in sync. */
export function relayDrift(plan = relayPlan()): string[] {
  const name = (file: string) => relative(APP, file);
  return [
    ...[...plan.write]
      .filter(([file, source]) => !existsSync(file) || readFileSync(file, "utf8") !== source)
      .map(([file]) => `${name(file)} differs from the route tables`),
    ...plan.remove.map((file) => `${name(file)} has no route in the tables`),
    ...plan.handWritten.map((file) => `${name(file)} relays by hand; declare it in a route table instead`),
  ];
}

function main(): void {
  const plan = relayPlan();
  if (process.argv.includes("--check")) {
    const drift = relayDrift(plan);
    if (drift.length) {
      console.error(`Relay route files are out of date. Run npm run generate:relay-routes -w @blast/web.\n${drift.join("\n")}`);
      process.exit(1);
    }
    return;
  }
  if (plan.handWritten.length) {
    console.error(relayDrift({ write: new Map(), remove: [], handWritten: plan.handWritten }).join("\n"));
    process.exit(1);
  }
  for (const [file, source] of plan.write) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, source);
  }
  for (const file of plan.remove) rmSync(file);
}

if (import.meta.main) main();
